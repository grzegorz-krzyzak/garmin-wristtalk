#!/bin/bash
# One command per build profile:
#   tools/build.sh dev      - simulator build; the house address default from .dev-house-url
#   tools/build.sh device   - the same for a real watch (sideloaded: no settings from Garmin Connect,
#                             so the house address is built in); closes when idle as set
#   tools/build.sh test     - unit tests (Run No Evil) in the running simulator
#   tools/build.sh release  - strict type check, no debug information, .iq for the store
#   tools/build.sh beta     - the same as a separate store app (its own id): a private beta, only for
#                             the developer's account
#   tools/build.sh run      - dev build, then start it in the simulator
#   tools/build.sh start    - start the last dev build again (simulator opened if needed), in the background;
#                             what the simulator prints goes to bin/simulator.log
set -euo pipefail
cd "$(dirname "$0")/.."
SDK="${CIQ_SDK:-$(cat "$HOME/Library/Application Support/Garmin/ConnectIQ/current-sdk.cfg" 2>/dev/null | sed 's:/*$::')}"
KEY="${CIQ_KEY:-$HOME/.connectiq/developer_key.der}"
DEVICE="${CIQ_DEVICE:-fenix8solar51mm}"
mkdir -p bin

# The manifest's version is the one the store shows; Settings.APP_VERSION the one the menu shows and
# Home Assistant gets - a package with two versions is not built
one_version() {
    local manifest code
    manifest=$(sed -n 's/.*<iq:application[^>]* version="\([^"]*\)".*/\1/p' manifest.xml)
    code=$(sed -n 's/.*const APP_VERSION = "\([^"]*\)".*/\1/p' source/logic/Settings.mc)
    [ -n "$manifest" ] && [ "$manifest" = "$code" ] || {
        echo "manifest.xml $manifest, Settings.APP_VERSION $code - make them the same" >&2
        exit 1
    }
}

dev_config() {
    local idle="${1:-300000}"
    local url=""
    [ -f .dev-house-url ] && url="$(tr -d '[:space:]' < .dev-house-url)"
    mkdir -p source-dev
    cat > source-dev/DevConfig.mc <<MC
import Toybox.Lang;

//! Dev build (generated by tools/build.sh, not in git): the simulator's default house address
function devHouseUrl() as String {
    return "$url";
}

//! Dev build: in the simulator stay open 5 minutes without input; 0 = the setting (device build)
function devIdleExitMs() as Number {
    return $idle;
}
MC
}

case "${1:-dev}" in
    dev|run)
        dev_config
        "$SDK/bin/monkeyc" -f "monkey.jungle;dev.jungle" -d "$DEVICE" -o bin/wristtalk.prg -y "$KEY" -l 3 -w
        if [ "${1:-dev}" = run ]; then
            pgrep -f "MacOS/simulator" >/dev/null || { open "$SDK/bin/ConnectIQ.app"; sleep 6; }
            "$SDK/bin/monkeydo" bin/wristtalk.prg "$DEVICE"
        fi
        ;;
    device)
        dev_config 0
        # The name the watch keeps: copying it over the old file leaves one WristTalk in GARMIN/APPS
        mkdir -p bin/device
        "$SDK/bin/monkeyc" -f "monkey.jungle;dev.jungle" -d "$DEVICE" -o bin/device/WRISTTALK.PRG -y "$KEY" -l 3 -w
        echo "bin/device/WRISTTALK.PRG - copy it to GARMIN/APPS on the watch, over the old WRISTTALK.PRG"
        ;;
    start)
        [ -f bin/wristtalk.prg ] || { echo "no build yet - run: $0 dev" >&2; exit 1; }
        pkill -f MonkeyDoDeux 2>/dev/null || true
        pgrep -f "MacOS/simulator" >/dev/null || { open "$SDK/bin/ConnectIQ.app"; sleep 7; }
        nohup "$SDK/bin/monkeydo" bin/wristtalk.prg "$DEVICE" >bin/simulator.log 2>&1 &
        echo "WristTalk started in the simulator (press START if it shows the glance)"
        ;;
    test)
        "$SDK/bin/monkeyc" -f "monkey.jungle;test.jungle" -d "$DEVICE" -o bin/wristtalk-test.prg -y "$KEY" --unit-test -l 2
        pgrep -f "MacOS/simulator" >/dev/null || { open "$SDK/bin/ConnectIQ.app"; sleep 6; }
        "$SDK/bin/monkeydo" bin/wristtalk-test.prg "$DEVICE" -t
        ;;
    release)
        one_version
        "$SDK/bin/monkeyc" -f monkey.jungle -e -r -l 3 -o bin/wristtalk.iq -y "$KEY"
        ;;
    beta)
        one_version
        # The store keeps a beta as its own app: the manifest with another id, nothing else differs
        sed 's/id="d106fb6d536e4d0f895290732d14ce5f"/id="6ab4b31f161c45e78416dda9360aefa8"/' manifest.xml > manifest-beta.xml
        grep -q 6ab4b31f161c45e78416dda9360aefa8 manifest-beta.xml || { echo "the app id in manifest.xml changed" >&2; exit 1; }
        # A jungle of its own (a project's manifest cannot be reset by a second jungle), at the root so
        # the resource folders are found as usual; generated, not in git
        printf 'project.manifest = manifest-beta.xml\nbase.sourcePath = source;source-app;source-release\n' > beta.jungle
        "$SDK/bin/monkeyc" -f beta.jungle -e -r -l 3 -o bin/wristtalk-beta.iq -y "$KEY"
        rm -f beta.jungle manifest-beta.xml
        echo "bin/wristtalk-beta.iq - upload it at apps-developer.garmin.com as a beta app"
        ;;
    *)
        echo "usage: $0 dev|device|run|start|test|release|beta" >&2
        exit 2
        ;;
esac
